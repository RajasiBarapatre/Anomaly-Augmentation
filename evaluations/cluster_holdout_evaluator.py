"""
Cluster-holdout evaluator

  This evaluator simulates hidden validation/test sets contain unseen attack types:
    1. The training attacks of a dataset are grouped into K = 8 pseudo attack types with k-means (log-scaled numeric features + one-hot categoricals, standardised)
    2. In each fold, 3 of the 8 groups are held out entirely as "unseen" attack types
    3. The generator sees 70% of the normal rows and 70% of the seen-type attacks (fold training part)
    4. The fold test set holds the other 30% of normals, the other 30% of seen-type attacks and all unseen-type attacks
    5. Each fold holds out a different set of 3 groups (folds 0, 1, 2 by default)

Commands to run:
  python cluster_holdout_evaluator.py                      # Both datasets, 3 folds
  python cluster_holdout_evaluator.py --dataset unsw       # 1 dataset
  python cluster_holdout_evaluator.py --folds 0            # 1 fold
  python cluster_holdout_evaluator.py --scoring official   # Official scoring instead of local

  --scoring local    (default) numeric columns raw + one-hot categoricals, ECOD and Isolation Forest (500 trees) with scores averaged over 3 seeds
  --scoring official  ECOD + Isolation Forest with AUPRC computed per seed over 10 seeds and averaged

Files generated:
  <dataset>/fold<k>/train.csv       fold training part (features + is_anomaly) given to the generator
  <dataset>/fold<k>/test.csv        fold test set (features + is_anomaly + pseudo_type + unseen)
  <dataset>/fold<k>/synthetic.csv   synthetic normals generated by final_augmentation_pipeline.py
  <dataset>/fold<k>/split.json      held-out pseudo-types and row counts
  results.csv                       1 row per dataset and fold
"""

import os
import sys
import json
import time
import argparse
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.cluster import KMeans
from sklearn.preprocessing import StandardScaler
from sklearn.ensemble import IsolationForest
from sklearn.metrics import average_precision_score

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import final_augmentation_pipeline as pipeline
from revised_experiment_config import DATASETS, OUTPUT_DIR
from revised_preprocessing import load_dataset, add_id_column
from revised_local_evaluator import evaluate_synthetic

#   Settings
#   K-means groups of training attacks
N_PSEUDO_TYPES = 8
#   Groups held out as unseen attack types in each fold    
N_UNSEEN = 3
#   Share of normals and seen-type attacks given to the generator             
TRAIN_FRACTION = 0.70
#   K-means seed
CLUSTER_SEED = 0
DEFAULT_FOLDS = [0, 1, 2]
#   Isolation Forest scores averaged over seeds 0-2
LOCAL_IFOREST_SEEDS = 3 
LOCAL_IFOREST_TREES = 500

EVAL_DIR = os.path.join(OUTPUT_DIR, "cluster_holdout")


def read_csv_exact(path):
    return pd.read_csv(path, float_precision="round_trip")


#   Fold generation
def _encode_for_clustering(df, numeric_cols, categorical_cols, levels):
    parts = [np.log1p(np.abs(df[numeric_cols].to_numpy(float)))]
    for c in categorical_cols:
        values = df[c].astype(str).to_numpy()[:, None]
        parts.append((values == np.array(levels[c])[None, :]).astype(float))
    return np.hstack(parts)


def make_fold(df, label_col, categorical_cols, fold):
    feature_cols = [c for c in df.columns if c != label_col]
    numeric_cols = [c for c in feature_cols if c not in categorical_cols]
    df = df.copy()
    for c in categorical_cols:
        df[c] = df[c].astype(str)
    levels = {c: sorted(df[c].unique()) for c in categorical_cols}

    attacks = df[df[label_col] == 1].copy()
    X_attack = _encode_for_clustering(attacks, numeric_cols, categorical_cols, levels)
    attacks["pseudo_type"] = KMeans(
        N_PSEUDO_TYPES, n_init=5, random_state=CLUSTER_SEED
    ).fit_predict(StandardScaler().fit_transform(X_attack))

    unseen = set(np.random.RandomState(100 + fold).permutation(N_PSEUDO_TYPES)[:N_UNSEEN].tolist())
    rng = np.random.RandomState(CLUSTER_SEED + fold)

    normals = df[df[label_col] == 0]
    normal_order = rng.permutation(len(normals))
    normal_cut = int(TRAIN_FRACTION * len(normals))

    seen_attacks = attacks[~attacks["pseudo_type"].isin(unseen)]
    attack_order = rng.permutation(len(seen_attacks))
    attack_cut = int(TRAIN_FRACTION * len(seen_attacks))

    train_df = pd.concat([
        normals.iloc[normal_order[:normal_cut]],
        seen_attacks.iloc[attack_order[:attack_cut]].drop(columns="pseudo_type"),
    ]).reset_index(drop=True)

    test_df = pd.concat([
        normals.iloc[normal_order[normal_cut:]].assign(pseudo_type=-1),
        seen_attacks.iloc[attack_order[attack_cut:]],
        attacks[attacks["pseudo_type"].isin(unseen)],
    ]).reset_index(drop=True)
    test_df["unseen"] = test_df["pseudo_type"].isin(unseen).astype(int)

    info = {
        "fold": fold,
        "unseen_pseudo_types": sorted(int(u) for u in unseen),
        "pseudo_type_sizes": {int(k): int(v) for k, v in attacks["pseudo_type"].value_counts().sort_index().items()},
        "train_rows": len(train_df),
        "train_normals": int((train_df[label_col] == 0).sum()),
        "train_attacks": int((train_df[label_col] == 1).sum()),
        "test_rows": len(test_df),
        "test_normals": int((test_df[label_col] == 0).sum()),
        "test_attacks_seen": int(((test_df[label_col] == 1) & (test_df["unseen"] == 0)).sum()),
        "test_attacks_unseen": int(test_df["unseen"].sum()),
    }
    return train_df, test_df, info


def fold_dir(dataset_key, fold):
    return Path(EVAL_DIR) / dataset_key / f"fold{fold}"


def step_split(dataset_key, folds):
    cfg = DATASETS[dataset_key]
    df, _ = load_dataset(cfg)
    df = df.drop(columns=["id"], errors="ignore")
    for fold in folds:
        out = fold_dir(dataset_key, fold)
        out.mkdir(parents=True, exist_ok=True)
        train_df, test_df, info = make_fold(df, cfg["label_col"], cfg["categorical_cols"], fold)
        train_df.to_csv(out / "train.csv", index=False)
        test_df.to_csv(out / "test.csv", index=False)
        (out / "split.json").write_text(json.dumps(info, indent=2))
        print(f"  [{dataset_key} fold {fold}] train {info['train_rows']:,} "
              f"({info['train_normals']:,} normal, {info['train_attacks']:,} attack) | "
              f"test {info['test_rows']:,} ({info['test_normals']:,} normal, "
              f"{info['test_attacks_seen']:,} seen-type, {info['test_attacks_unseen']:,} unseen-type attacks) | "
              f"unseen pseudo-types {info['unseen_pseudo_types']}")

#  Synthetic generation
def generate_like_run(train_df, dataset_key):
    cfg = DATASETS[dataset_key]
    _, col_types = load_dataset(cfg)

    pipeline.HYBRID_RFOD_WEIGHT = pipeline.HYBRID_RFOD_WEIGHTS[dataset_key]
    pipeline.REWEIGHT_STRENGTH = pipeline.REWEIGHT_STRENGTHS[dataset_key]

    def generate_fn(frame):
        return pipeline.generate_dataset_synthetic_normals(
            frame,
            cfg["label_col"],
            col_types,
            cfg["target_n"],
            seed=pipeline.GENERATION_SEEDS[dataset_key],
            candidate_over_sample_factor=pipeline.CANDIDATE_OVER_SAMPLE_FACTORS[dataset_key],
            realism_weight=pipeline.REALISM_WEIGHTS[dataset_key],
            mixture_adapt_strength=pipeline.MIXTURE_ADAPT_STRENGTHS[dataset_key],
            attack_overlap_percentile=pipeline.ATTACK_OVERLAP_PERCENTILES[dataset_key],
            use_tvae=pipeline.USE_TVAE[dataset_key],
            coverage_filter=pipeline.COVERAGE_FILTER[dataset_key],
            empirical_share=pipeline.EMPIRICAL_SHARES[dataset_key],
            base_mixture=pipeline.BASE_MIXTURES[dataset_key],
        )

    synthetic = generate_fn(train_df)
    synthetic = pipeline.reweight_stage(
        train_df, cfg["label_col"], col_types["all_feature"], cfg["categorical_cols"],
        synthetic, generate_fn, anchor_mode=pipeline.REWEIGHT_ANCHOR[dataset_key],
    )
    synthetic = synthetic.drop(columns=["id"], errors="ignore")[col_types["all_feature"]]
    return add_id_column(synthetic.reset_index(drop=True))


def step_generate(dataset_key, folds):
    for fold in folds:
        out = fold_dir(dataset_key, fold)
        if not (out / "train.csv").exists():
            raise FileNotFoundError(f"{out / 'train.csv'} not found. Run with --step split first.")
        train_df = read_csv_exact(out / "train.csv")
        print(f"\n  [{dataset_key} fold {fold}] generating with final_augmentation_pipeline.py "
              f"(RFOD weight {pipeline.HYBRID_RFOD_WEIGHTS[dataset_key]}, "
              f"re-weighting {pipeline.REWEIGHT_STRENGTHS[dataset_key]}, "
              f"mixture {pipeline.BASE_MIXTURES[dataset_key]}) ...")
        t0 = time.time()
        synthetic = generate_like_run(train_df, dataset_key)
        synthetic.to_csv(out / "synthetic.csv", index=False)
        print(f"  [{dataset_key} fold {fold}] wrote {len(synthetic):,} synthetic rows "
              f"to {out / 'synthetic.csv'} ({time.time() - t0:.0f}s)")

#   Scoring
def _local_encode(df, numeric_cols, categorical_cols, levels):
    """Numeric columns raw + one-hot categoricals over the full dataset's category levels."""
    parts = [df[numeric_cols].to_numpy(float)]
    for c in categorical_cols:
        values = df[c].astype(str).to_numpy()[:, None]
        parts.append((values == np.array(levels[c])[None, :]).astype(float))
    return np.hstack(parts)


def local_score(synthetic, test_df, label_col, numeric_cols, categorical_cols, levels):
    from pyod.models.ecod import ECOD
    X_syn = _local_encode(synthetic, numeric_cols, categorical_cols, levels)
    X_test = _local_encode(test_df, numeric_cols, categorical_cols, levels)
    y = test_df[label_col].to_numpy()
    ecod_scores = ECOD().fit(X_syn).decision_function(X_test)
    iforest_scores = np.mean([
        -IsolationForest(n_estimators=LOCAL_IFOREST_TREES, random_state=s).fit(X_syn).score_samples(X_test)
        for s in range(LOCAL_IFOREST_SEEDS)
    ], axis=0)
    auprc_ecod = average_precision_score(y, ecod_scores)
    auprc_if = average_precision_score(y, iforest_scores)
    return {"score_S": (auprc_ecod + auprc_if) / 2, "auprc_ecod": auprc_ecod, "auprc_iforest_mean": auprc_if}


def step_score(dataset_key, folds, scoring="local"):
    cfg = DATASETS[dataset_key]
    label_col, cats = cfg["label_col"], cfg["categorical_cols"]
    full_df, _ = load_dataset(cfg)
    full_df = full_df.drop(columns=["id"], errors="ignore")
    feature_cols = [c for c in full_df.columns if c != label_col]
    numeric_cols = [c for c in feature_cols if c not in cats]
    levels = {c: sorted(full_df[c].astype(str).unique()) for c in cats}

    def score_fn(syn, test):
        if scoring == "official":
            return evaluate_synthetic(syn, test, cats, label_col, verbose=False)
        return local_score(syn.drop(columns=["id"], errors="ignore"), test, label_col, numeric_cols, cats, levels)

    rows = []
    for fold in folds:
        out = fold_dir(dataset_key, fold)
        if not (out / "synthetic.csv").exists():
            raise FileNotFoundError(f"{out / 'synthetic.csv'} not found. Run with --step generate first.")
        synthetic = read_csv_exact(out / "synthetic.csv")
        test_df = read_csv_exact(out / "test.csv")
        flags = test_df[["pseudo_type", "unseen"]]
        test_df = test_df.drop(columns=["pseudo_type", "unseen"])

        t0 = time.time()
        overall = score_fn(synthetic, test_df)
        mask = (test_df[label_col] == 0) | (flags["unseen"] == 1)
        unseen = score_fn(synthetic, test_df[mask.to_numpy()].reset_index(drop=True))
        row = {
            "dataset": dataset_key,
            "fold": fold,
            "scoring": scoring,
            "S": overall["score_S"],
            "AUPRC_ECOD": overall["auprc_ecod"],
            "AUPRC_IForest": overall["auprc_iforest_mean"],
            "S_unseen": unseen["score_S"],
            "test_attack_share": float(test_df[label_col].mean()),
            "synthetic_rows": len(synthetic),
        }
        rows.append(row)
        print(f"  [{dataset_key} fold {fold}] S={row['S']:.5f}  ECOD={row['AUPRC_ECOD']:.5f}  "
              f"IForest={row['AUPRC_IForest']:.5f}  S_unseen={row['S_unseen']:.5f}  ({time.time() - t0:.0f}s)")
    return rows


def main():
    parser = argparse.ArgumentParser(description="Cluster-holdout evaluation (unseen attack types simulated).")
    parser.add_argument("--dataset", choices=["nslkdd", "unsw", "both"], default="both")
    parser.add_argument("--folds", default=",".join(str(f) for f in DEFAULT_FOLDS),
                        help="comma-separated fold numbers, e.g. 0,1,2")
    parser.add_argument("--step", choices=["all", "split", "generate", "score"], default="all")
    parser.add_argument("--scoring", choices=["local", "official"], default="local",
                        help="local: 3 seeds, scores averaged "
                             "official: 10 seeds, AUPRC averaged")
    args = parser.parse_args()

    folds = [int(f) for f in args.folds.split(",") if f.strip() != ""]
    datasets = ["nslkdd", "unsw"] if args.dataset == "both" else [args.dataset]
    Path(EVAL_DIR).mkdir(parents=True, exist_ok=True)

    print("=" * 72)
    print(f"Cluster-holdout evaluation: {N_PSEUDO_TYPES} pseudo attack types, {N_UNSEEN} held out per fold, "
          f"{TRAIN_FRACTION:.0%} train / {1 - TRAIN_FRACTION:.0%} test")
    print(f"Datasets: {datasets} | folds: {folds} | step: {args.step} | scoring: {args.scoring} | output: {EVAL_DIR}")
    print("=" * 72)

    results = []
    for dataset_key in datasets:
        print(f"\n### {DATASETS[dataset_key]['name']}")
        if args.step in ("all", "split"):
            step_split(dataset_key, folds)
        if args.step in ("all", "generate"):
            step_generate(dataset_key, folds)
        if args.step in ("all", "score"):
            results.extend(step_score(dataset_key, folds, scoring=args.scoring))

    if results:
        res = pd.DataFrame(results)
        path = Path(EVAL_DIR) / "results.csv"
        if path.exists():
            old = pd.read_csv(path)
            keep = ~old.set_index(["dataset", "fold"]).index.isin(res.set_index(["dataset", "fold"]).index)
            res = pd.concat([old[keep], res]).sort_values(["dataset", "fold"]).reset_index(drop=True)
        res.to_csv(path, index=False)

        print("\n" + "=" * 72)
        print("Summary (mean over folds scored in this run)")
        summary = pd.DataFrame(results).groupby("dataset")[["S", "AUPRC_ECOD", "AUPRC_IForest", "S_unseen"]].mean()
        print(summary.round(5).to_string())
        print(f"\nAll results: {path}")


if __name__ == "__main__":
    main()
